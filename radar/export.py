"""Outbound integrations: proxy blocklist + SIEM-friendly JSONL."""
import json
import re

_HOST = re.compile(r"^[a-z0-9]([a-z0-9.-]{0,251}[a-z0-9])?$")


def blocklist(db, path):
    """Squid-style dstdomain list of every non-sanctioned AI host seen. Review before enforcing."""
    hosts = [r[0] for r in db.execute(
        "SELECT DISTINCT host FROM silver_events WHERE is_ai=1 AND status!='sanctioned' ORDER BY host")]
    hosts = [h for h in hosts if _HOST.match(h)]  # logs are untrusted: never write a line that could inject proxy config
    with open(path, "w") as f:
        f.write("# generated by Shadow-AI Radar: review before enforcing\n")
        f.writelines(f".{h}\n" for h in hosts)
    return len(hosts)


def siem(alerts, path):
    sev = {"critical": 90, "high": 70, "medium": 50, "low": 20}
    with open(path, "w") as f:
        for a in alerts:
            f.write(json.dumps({"event.kind": "alert", "event.id": a["alert_id"], "event.category": a["kind"],
                                "event.severity": sev[a["severity"]], "user.name": a["user"], "@timestamp": a["day"],
                                "message": a["title"], "event.outcome": a["status"], "rule.description": a["action"]}) + "\n")
    return len(alerts)


def _safe(v):
    """CSV/formula-injection guard: Excel/Sheets execute cells starting with = + - @ (also tab/CR). Analyst notes and
    service names are attacker-influenced, so neutralise them with a leading apostrophe."""
    s = "" if v is None else str(v)
    return "'" + s if s[:1] in ("=", "+", "-", "@", "\t", "\r") else s


def alerts_csv(alerts, path):
    import csv
    cols = ["alert_id", "severity", "kind", "day", "user", "manager", "title", "evidence", "action", "count", "status", "note"]
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for a in alerts:
            w.writerow([_safe(a.get(c)) for c in cols])
    return len(alerts)


def audit_csv(db, path):
    """Full audit log incl. hashes, so an auditor can re-verify the chain independently."""
    import csv
    from . import audit
    db.execute(audit.DDL)
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "ts", "actor", "action", "target", "detail", "prev_hash", "hash"])
        n = 0
        for row in db.execute("SELECT id,ts,actor,action,target,detail,prev_hash,hash FROM audit_log ORDER BY id"):
            w.writerow([_safe(v) if i in (2, 3, 4, 5) else v for i, v in enumerate(row)])
            n += 1
    return n
